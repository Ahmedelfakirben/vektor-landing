// Available languages
export const SUPPORTED_LANGUAGES = [
  { code: 'es', label: 'Español', flag: '🇪🇸' },
  { code: 'fr', label: 'Français', flag: '🇫🇷' },
  { code: 'en', label: 'English', flag: '🇬🇧' }
];

export function getActiveLanguage() {
  const saved = localStorage.getItem('vektor_lang');
  if (saved && ['es', 'fr', 'en'].includes(saved)) {
    return saved;
  }
  const browserLang = (navigator.language || '').toLowerCase();
  if (browserLang.startsWith('fr')) return 'fr';
  if (browserLang.startsWith('en')) return 'en';
  return 'es';
}

export function setLanguage(lang) {
  if (!['es', 'fr', 'en'].includes(lang)) return;
  localStorage.setItem('vektor_lang', lang);
  document.documentElement.lang = lang;

  const dict = translations[lang] || translations.es;

  // Translate all [data-i18n]
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Translate all [data-i18n-html]
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // Translate placeholders [data-i18n-placeholder]
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Update switcher UI
  const currentLangBtn = document.getElementById('currentLangLabel');
  const currentFlag = document.getElementById('currentLangFlag');
  const langObj = SUPPORTED_LANGUAGES.find(l => l.code === lang);
  if (currentLangBtn && langObj) {
    currentLangBtn.textContent = langObj.code.toUpperCase();
  }
  if (currentFlag && langObj) {
    currentFlag.textContent = langObj.flag;
  }

  // Update active state in dropdown
  document.querySelectorAll('.lang-dropdown-item').forEach(item => {
    const itemCode = item.getAttribute('data-lang');
    if (itemCode === lang) {
      item.classList.add('active');
    } else {
      item.classList.remove('active');
    }
  });

  // Dispatch custom event for dynamic components
  window.dispatchEvent(new CustomEvent('vektor_language_changed', { detail: { lang } }));
}
